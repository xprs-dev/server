// Sync lib/version.dart from pubspec.yaml's `version: X.Y.Z`.
// Run from the project root: `dart run tool/update_version.dart`.
// A test (test/update_test.dart) fails when the two disagree, so a release
// cannot ship a binary that reports the wrong version to the updater.
import 'dart:io';

void main() {
  final line = File('pubspec.yaml').readAsLinesSync().firstWhere(
        (l) => l.trimLeft().startsWith('version:'),
        orElse: () => '',
      );
  if (line.isEmpty) {
    stderr.writeln('No version: line in pubspec.yaml');
    exit(1);
  }
  final version = line.split(':')[1].trim().split('+').first;
  File('lib/version.dart').writeAsStringSync('''
// GENERATED by tool/update_version.dart from pubspec.yaml; do not edit by hand.
//
// kServerVersion is what `xprs-server --version` prints and what the updater
// (lib/update/updater.dart) compares with the newest GitHub release.

const String kServerVersion = '$version';
''');
  stdout.writeln('lib/version.dart: $version');
}
